CREATE TABLE users (
 user_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_users PRIMARY KEY,
 name VARCHAR2(100) CONSTRAINT nn_users_name NOT NULL,
 email VARCHAR2(150) CONSTRAINT nn_users_email NOT NULL CONSTRAINT uq_users_email UNIQUE,
 role VARCHAR2(50) DEFAULT 'DEVELOPER' CONSTRAINT nn_users_role NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP CONSTRAINT nn_users_created NOT NULL,
 CONSTRAINT chk_users_role CHECK (role IN ('DEVELOPER','ARCHITECT','QA','ADMIN','TECH_LEAD')));
CREATE TABLE agents (
 agent_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_agents PRIMARY KEY,
 agent_name VARCHAR2(100) CONSTRAINT nn_agents_name NOT NULL CONSTRAINT uq_agents_name UNIQUE,
 model_name VARCHAR2(100) CONSTRAINT nn_agents_model NOT NULL,
 model_version VARCHAR2(50) DEFAULT '1.0' CONSTRAINT nn_agents_version NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP CONSTRAINT nn_agents_created NOT NULL);
CREATE TABLE projects (
 project_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_projects PRIMARY KEY,
 project_name VARCHAR2(150) CONSTRAINT nn_projects_name NOT NULL CONSTRAINT uq_projects_name UNIQUE,
 description VARCHAR2(1000) CONSTRAINT nn_projects_description NOT NULL,
 status VARCHAR2(30) DEFAULT 'ACTIVE' CONSTRAINT nn_projects_status NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP CONSTRAINT nn_projects_created NOT NULL,
 CONSTRAINT chk_projects_status CHECK(status IN ('ACTIVE','ON_HOLD','COMPLETED','ARCHIVED')));
CREATE TABLE sessions (
 session_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_sessions PRIMARY KEY,
 user_id NUMBER CONSTRAINT nn_sessions_user NOT NULL,
 agent_id NUMBER CONSTRAINT nn_sessions_agent NOT NULL,
 project_id NUMBER CONSTRAINT nn_sessions_project NOT NULL,
 start_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP CONSTRAINT nn_sessions_start NOT NULL,
 end_time TIMESTAMP, status VARCHAR2(30) DEFAULT 'ACTIVE' CONSTRAINT nn_sessions_status NOT NULL,
 CONSTRAINT fk_sessions_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE CASCADE,
 CONSTRAINT fk_sessions_agent FOREIGN KEY(agent_id) REFERENCES agents(agent_id) ON DELETE CASCADE,
 CONSTRAINT fk_sessions_project FOREIGN KEY(project_id) REFERENCES projects(project_id) ON DELETE CASCADE,
 CONSTRAINT chk_sessions_status CHECK(status IN ('ACTIVE','COMPLETED','ABORTED')),
 CONSTRAINT chk_session_times CHECK(end_time IS NULL OR end_time >= start_time));
CREATE TABLE tasks (
 task_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_tasks PRIMARY KEY,
 project_id NUMBER CONSTRAINT nn_tasks_project NOT NULL, agent_id NUMBER,
 title VARCHAR2(200) CONSTRAINT nn_tasks_title NOT NULL, description VARCHAR2(1000) CONSTRAINT nn_tasks_description NOT NULL,
 priority VARCHAR2(20) DEFAULT 'MEDIUM' CONSTRAINT nn_tasks_priority NOT NULL,
 status VARCHAR2(30) DEFAULT 'OPEN' CONSTRAINT nn_tasks_status NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP CONSTRAINT nn_tasks_created NOT NULL, completed_at TIMESTAMP,
 CONSTRAINT fk_tasks_project FOREIGN KEY(project_id) REFERENCES projects(project_id) ON DELETE CASCADE,
 CONSTRAINT fk_tasks_agent FOREIGN KEY(agent_id) REFERENCES agents(agent_id) ON DELETE SET NULL,
 CONSTRAINT chk_tasks_priority CHECK(priority IN ('LOW','MEDIUM','HIGH','CRITICAL')),
 CONSTRAINT chk_tasks_status CHECK(status IN ('OPEN','IN_PROGRESS','COMPLETED','BLOCKED')));
CREATE TABLE memories (
 memory_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_memories PRIMARY KEY,
 project_id NUMBER CONSTRAINT nn_memories_project NOT NULL, session_id NUMBER, task_id NUMBER,
 title VARCHAR2(200) CONSTRAINT nn_memories_title NOT NULL, content CLOB CONSTRAINT nn_memories_content NOT NULL,
 memory_type VARCHAR2(40) CONSTRAINT nn_memories_type NOT NULL,
 importance NUMBER(1) DEFAULT 3 CONSTRAINT nn_memories_importance NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP CONSTRAINT nn_memories_created NOT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP CONSTRAINT nn_memories_updated NOT NULL,
 CONSTRAINT fk_memories_project FOREIGN KEY(project_id) REFERENCES projects(project_id) ON DELETE CASCADE,
 CONSTRAINT fk_memories_session FOREIGN KEY(session_id) REFERENCES sessions(session_id) ON DELETE SET NULL,
 CONSTRAINT fk_memories_task FOREIGN KEY(task_id) REFERENCES tasks(task_id) ON DELETE SET NULL,
 CONSTRAINT chk_memories_type CHECK(memory_type IN ('REQUIREMENT','DECISION','CONSTRAINT','BUG','SOLUTION','FINDING','RULE')),
 CONSTRAINT chk_memory_importance CHECK(importance BETWEEN 1 AND 5));
CREATE TABLE tags (
 tag_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_tags PRIMARY KEY,
 tag_name VARCHAR2(60) CONSTRAINT nn_tags_name NOT NULL CONSTRAINT uq_tags_name UNIQUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP CONSTRAINT nn_tags_created NOT NULL);
CREATE TABLE memory_tags (
 memory_id NUMBER CONSTRAINT nn_mtags_memory NOT NULL, tag_id NUMBER CONSTRAINT nn_mtags_tag NOT NULL,
 CONSTRAINT pk_memory_tags PRIMARY KEY(memory_id,tag_id),
 CONSTRAINT fk_mtags_memory FOREIGN KEY(memory_id) REFERENCES memories(memory_id) ON DELETE CASCADE,
 CONSTRAINT fk_mtags_tag FOREIGN KEY(tag_id) REFERENCES tags(tag_id) ON DELETE CASCADE);
CREATE INDEX idx_memories_lookup ON memories(project_id,memory_type,importance);
CREATE INDEX idx_tasks_lookup ON tasks(project_id,status);
CREATE INDEX idx_sessions_user ON sessions(user_id);
CREATE INDEX idx_sessions_agent ON sessions(agent_id);
CREATE INDEX idx_memories_task ON memories(task_id);
EXIT;
